import {chromium} from '@playwright/test';
import fs from 'node:fs';
const base=process.env.TEST_BASE_URL||'https://summitwar.lol';
const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--disable-gpu']});
const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[],writes=[];
page.on('pageerror',error=>errors.push(error.stack||error.message));
page.on('request',request=>{if(request.method()==='POST'&&/\/api\/(command|promotions|vote|stripe)(\/|$)/.test(new URL(request.url()).pathname))writes.push(request.url())});
const check=(ok,message)=>{if(!ok)throw Error(message)};
try{
 const response=await page.goto(`${base}/demo`,{waitUntil:'load',timeout:60000});
 check(response.status()===200,'Demo page did not load');
 await page.getByRole('heading',{name:'The winner’s circle.'}).waitFor();
 check(await page.getByText('DEMO PREVIEW',{exact:true}).count()===1,'Sample data must be clearly labeled');
 check((await page.locator('meta[name=robots]').getAttribute('content')).includes('noindex'),'Demo should not be indexed');
 check(await page.locator('.promotion-occupied').count()===6,'All six sample sponsorships must be filled');
 check(await page.locator('.promotion-empty').count()===0,'Filled demo should have no empty sponsor cards');
 check(await page.locator('.hero-winner h2').innerText()==='Forgepad','Champion must occupy the center');
 check(await page.locator('.match-slot.ready').count()===7,'Completed bracket needs all seven matches');
 check(await page.locator('.participant-row').count()===1,'After the final, only the champion row should be shown');
 check(await page.locator('.participant-votes b').innerText()==='684','Champion should show the sample final votes');
 check(await page.locator('.tournament-watch').innerText().then(text=>text.includes('Winner spotlight ends in')),'Winner spotlight countdown missing');
 const before=page.url();
 await page.locator('.promotion-occupied a').first().click();
 await page.getByRole('dialog',{name:'Kilo CRM',exact:true}).waitFor();
 check(page.url()===before,'Demo sponsor must open sample details without navigation');
 await page.keyboard.press('Escape');
 await page.getByRole('link',{name:'Meet the winner',exact:false}).click();
 await page.getByRole('dialog',{name:'Forgepad',exact:true}).waitFor();
 await page.getByRole('button',{name:'Close demo details'}).click();
 await page.locator('.final-center .slot-app').first().click();
 const final=page.getByRole('dialog',{name:'The final',exact:true});
 await final.waitFor();
 check((await final.innerText()).includes('684 sample votes')&&(await final.innerText()).includes('526 sample votes'),'Sample final score incorrect');
 await page.keyboard.press('Escape');
 await page.locator('.participant-row').scrollIntoViewIfNeeded();
 await page.getByRole('link',{name:'Sign in to follow or save',exact:false}).click();
 await page.getByRole('dialog',{name:'A preview of the finished tournament',exact:true}).waitFor();
 await page.keyboard.press('Escape');
 check(page.url()===before&&writes.length===0,'Demo must not write votes, orders or project actions');
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('.demo-preview img')).every(image=>image.complete&&image.naturalWidth>0));
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Desktop demo has horizontal overflow');
 await page.screenshot({path:'artifacts/final-look-desktop.png',fullPage:true});
 const heroBottom=await page.locator('.summit-hero').evaluate(element=>element.getBoundingClientRect().bottom+scrollY);
 await page.screenshot({path:'artifacts/final-look-hero.png',clip:{x:0,y:0,width:1440,height:Math.ceil(heroBottom)}});
 await page.setViewportSize({width:390,height:844});
 await page.locator('.participant-row').scrollIntoViewIfNeeded();
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile demo has horizontal overflow');
 const winner=await page.locator('.hero-winner').boundingBox(),promotions=await page.locator('.promotion-left').boundingBox();
 check(winner.y<promotions.y,'Champion should appear first on mobile');
 await page.screenshot({path:'artifacts/final-look-mobile.png',fullPage:true});
 check(errors.length===0,errors.join('\n'));
 const result={passed:true,site:`${base}/demo`,scope:'Clearly labeled fictional preview; no database seeding, payments or votes submitted.',checks:['six filled sponsors','central champion','seven completed matches','one champion row','sample final score','spotlight countdown','sample project and match dialogs','no preview writes or external navigation','noindex metadata','desktop and mobile without overflow','no page errors']};
 fs.writeFileSync('artifacts/final-look-browser.json',JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result,null,2));
}finally{await browser.close()}
